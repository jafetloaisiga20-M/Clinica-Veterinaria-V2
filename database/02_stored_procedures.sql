/* ============================================================
   CLIENTES
   ============================================================ */

CREATE OR ALTER PROCEDURE dbo.SP_LISTAR_CLIENTES
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_CLIENTE, NOMBRE_COMPLETO, TELEFONO, WHATSAPP, EMAIL, DIRECCION, ESTADO
    FROM dbo.CLIENTE
    ORDER BY ID_CLIENTE;
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_NUEVO_CLIENTE
    @NOMBRE_COMPLETO NVARCHAR(150),
    @TELEFONO        NVARCHAR(30) = NULL,
    @WHATSAPP        NVARCHAR(30) = NULL,
    @EMAIL           NVARCHAR(120) = NULL,
    @DIRECCION       NVARCHAR(200) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    IF @NOMBRE_COMPLETO IS NULL OR LTRIM(RTRIM(@NOMBRE_COMPLETO)) = ''
    BEGIN
        ;THROW 50001, 'El nombre del cliente es obligatorio.', 1;
    END

    INSERT INTO dbo.CLIENTE (NOMBRE_COMPLETO, TELEFONO, WHATSAPP, EMAIL, DIRECCION, ESTADO)
    VALUES (@NOMBRE_COMPLETO, @TELEFONO, @WHATSAPP, @EMAIL, @DIRECCION, N'Activo');

    SELECT CAST(SCOPE_IDENTITY() AS INT);
END
GO

