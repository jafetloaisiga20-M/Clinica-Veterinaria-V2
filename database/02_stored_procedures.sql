CREATE OR ALTER PROCEDURE dbo.SP_LISTAR_FACTURA
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_FACTURA, ID_CITA, ID_CLIENTE, NUMERO_FACTURA, TICKET_IMPRESO,
           FECHA_EMISION, SUBTOTAL, IMPUESTOS, TOTAL_PAGAR, METODO_PAGO, ESTADO_FACTURA
    FROM dbo.FACTURA
    ORDER BY ID_FACTURA DESC;
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_NUEVA_FACTURA
    @ID_CITA         INT,
    @ID_CLIENTE      INT,
    @SUB_TOTAL       DECIMAL(10,2),
    @IMPUESTOS       DECIMAL(10,2),
    @TOTAL_PAGAR     DECIMAL(10,2),
    @METODO_DE_PAGO  NVARCHAR(40) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM dbo.CITA WHERE ID_CITAS = @ID_CITA)
    BEGIN
        ;THROW 50011, 'La cita indicada no existe.', 1;
    END

    IF NOT EXISTS (SELECT 1 FROM dbo.CLIENTE WHERE ID_CLIENTE = @ID_CLIENTE)
    BEGIN
        ;THROW 50012, 'El cliente indicado no existe.', 1;
    END

    INSERT INTO dbo.FACTURA
        (ID_CITA, ID_CLIENTE, NUMERO_FACTURA, TICKET_IMPRESO, FECHA_EMISION,
         SUBTOTAL, IMPUESTOS, TOTAL_PAGAR, METODO_PAGO, ESTADO_FACTURA)
    VALUES
        (@ID_CITA, @ID_CLIENTE, NULL, 0, SYSDATETIME(),
         @SUB_TOTAL, @IMPUESTOS, @TOTAL_PAGAR, @METODO_DE_PAGO, N'Emitida');

    DECLARE @ID_FACTURA INT = SCOPE_IDENTITY();

    UPDATE dbo.FACTURA
    SET NUMERO_FACTURA = N'FAC-'
        + CONVERT(NVARCHAR(8), SYSDATETIME(), 112)
        + N'-'
        + RIGHT(N'0000' + CONVERT(NVARCHAR(10), @ID_FACTURA), 4)
    WHERE ID_FACTURA = @ID_FACTURA;
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_ANULAR_FACTURA
    @ID INT
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE dbo.FACTURA
    SET ESTADO_FACTURA = N'Anulada'
    WHERE ID_FACTURA = @ID;
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_LISTAR_DETALLE_POR_FACTURA
AS
BEGIN
    SET NOCOUNT ON;

    SELECT df.ID_FACTURA,
           f.FECHA_EMISION,
           c.NOMBRE_COMPLETO,
           df.ID_SERVICIO,
           df.CANTIDAD,
           df.PRECIO_UNITARIO,
           df.SUBTOTAL_LINEA,
           f.ESTADO_FACTURA
    FROM dbo.DETALLE_FACTURA df
    INNER JOIN dbo.FACTURA f ON f.ID_FACTURA = df.ID_FACTURA
    INNER JOIN dbo.CLIENTE c ON c.ID_CLIENTE = f.ID_CLIENTE
    ORDER BY df.ID_FACTURA DESC, df.ID_DETALLE;
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_NUEVA_DETALLE_FACTURA
    @ID_FACTURA   INT,
    @ID_SERVICIO  INT,
    @CANTIDAD     INT
AS
BEGIN
    SET NOCOUNT ON;

    IF @CANTIDAD IS NULL OR @CANTIDAD <= 0
    BEGIN
        ;THROW 50013, 'La cantidad debe ser mayor que cero.', 1;
    END

    IF EXISTS (SELECT 1 FROM dbo.FACTURA WHERE ID_FACTURA = @ID_FACTURA AND ESTADO_FACTURA = N'Anulada')
    BEGIN
        ;THROW 50014, 'No se pueden agregar lineas a una factura anulada.', 1;
    END

    DECLARE @PRECIO DECIMAL(10,2) =
    (
        SELECT PRECIO
        FROM dbo.SERVICIO
        WHERE ID_SERVICIO = @ID_SERVICIO
          AND ESTADO = N'Activo'
    );

    IF @PRECIO IS NULL
    BEGIN
        ;THROW 50015, 'El servicio indicado no existe o esta inactivo.', 1;
    END

    INSERT INTO dbo.DETALLE_FACTURA (ID_FACTURA, ID_SERVICIO, CANTIDAD, PRECIO_UNITARIO)
    VALUES (@ID_FACTURA, @ID_SERVICIO, @CANTIDAD, @PRECIO);
END
GO

