IF OBJECT_ID(N'dbo.FACTURA', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.FACTURA
    (
        ID_FACTURA        INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_FACTURA PRIMARY KEY,
        ID_CITA           INT NOT NULL,
        ID_CLIENTE        INT NOT NULL,
        NUMERO_FACTURA    NVARCHAR(30) NULL,
        TICKET_IMPRESO    BIT NOT NULL CONSTRAINT DF_FACTURA_TICKET DEFAULT (0),
        FECHA_EMISION     DATETIME2(0) NOT NULL CONSTRAINT DF_FACTURA_FECHA DEFAULT (SYSDATETIME()),
        SUBTOTAL          DECIMAL(10,2) NOT NULL CONSTRAINT DF_FACTURA_SUBTOTAL DEFAULT (0),
        IMPUESTOS         DECIMAL(10,2) NOT NULL CONSTRAINT DF_FACTURA_IMPUESTOS DEFAULT (0),
        TOTAL_PAGAR       DECIMAL(10,2) NOT NULL CONSTRAINT DF_FACTURA_TOTAL DEFAULT (0),
        METODO_PAGO       NVARCHAR(40) NULL,
        ESTADO_FACTURA    NVARCHAR(20) NOT NULL CONSTRAINT DF_FACTURA_ESTADO DEFAULT (N'Emitida'),
        CONSTRAINT FK_FACTURA_CITA FOREIGN KEY (ID_CITA) REFERENCES dbo.CITA (ID_CITAS),
        CONSTRAINT FK_FACTURA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES dbo.CLIENTE (ID_CLIENTE),
        CONSTRAINT CK_FACTURA_TOTAL CHECK (TOTAL_PAGAR >= 0)
    );

    CREATE UNIQUE INDEX UX_FACTURA_NUMERO
        ON dbo.FACTURA (NUMERO_FACTURA)
        WHERE NUMERO_FACTURA IS NOT NULL;

    CREATE INDEX IX_FACTURA_CLIENTE ON dbo.FACTURA (ID_CLIENTE);
    CREATE INDEX IX_FACTURA_CITA ON dbo.FACTURA (ID_CITA);
END
GO

IF OBJECT_ID(N'dbo.DETALLE_FACTURA', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.DETALLE_FACTURA
    (
        ID_DETALLE        INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_DETALLE_FACTURA PRIMARY KEY,
        ID_FACTURA        INT NOT NULL,
        ID_SERVICIO       INT NOT NULL,
        CANTIDAD          INT NOT NULL CONSTRAINT DF_DETALLE_CANTIDAD DEFAULT (1),
        PRECIO_UNITARIO   DECIMAL(10,2) NOT NULL,
        SUBTOTAL_LINEA    AS (CAST(CANTIDAD * PRECIO_UNITARIO AS DECIMAL(10,2))) PERSISTED,
        CONSTRAINT FK_DETALLE_FACTURA FOREIGN KEY (ID_FACTURA) REFERENCES dbo.FACTURA (ID_FACTURA),
        CONSTRAINT FK_DETALLE_SERVICIO FOREIGN KEY (ID_SERVICIO) REFERENCES dbo.SERVICIO (ID_SERVICIO),
        CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0)
    );

    CREATE INDEX IX_DETALLE_FACTURA ON dbo.DETALLE_FACTURA (ID_FACTURA);
    CREATE INDEX IX_DETALLE_SERVICIO ON dbo.DETALLE_FACTURA (ID_SERVICIO);
END
GO

